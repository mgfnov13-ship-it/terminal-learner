export type MessageKey = keyof (typeof messages)['ar'];
export const MESSAGE_KEYS = Object.keys(messages.ar) as MessageKey[];

export function message(language: Language, key: MessageKey): string {
  return messages[language][key];
}

export function localize(language: Language, value: LocalizedText): string {
  return value[language];
}

export function direction(language: Language): 'rtl' | 'ltr' {
  return language === 'ar' ? 'rtl' : 'ltr';
}

export function tx(en: string, ar: string): LocalizedText {
  return { en, ar };
}

export function uiLanguage(): Language {
  if (typeof document === 'undefined') return 'en';
  return document.documentElement.lang === 'ar' ? 'ar' : 'en';
}

export function pickUi(value: LocalizedText): string {
  return value[uiLanguage()];
}

export function L(en: string, ar: string): string {
  return uiLanguage() === 'ar' ? ar : en;
}
